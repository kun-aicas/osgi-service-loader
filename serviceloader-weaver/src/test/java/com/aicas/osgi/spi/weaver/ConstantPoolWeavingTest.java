  /**
   * Changes the class from {@link #consumer()} into an interface, equivalent to:
   *
   * <pre>{@code
   * public interface Consumer {
   *   static java.util.ServiceLoader load() {
   *     return java.util.ServiceLoader.load(Runnable.class);
   *   }
   * }
   * }</pre>
   *
   * <p>After weaving, the return type is remapped and the call targets a private
   * static bridge.</p>
   * <pre>{@code
   * public interface Consumer {
   *   static com.aicas.osgi.spi.proxy.ServiceLoader load() {
   *     return Consumer.serviceLoaderBridge$load(Runnable.class);
   *   }
   *
   *   private static com.aicas.osgi.spi.proxy.ServiceLoader serviceLoaderBridge$load(Class service) {
   *     return com.aicas.osgi.spi.proxy.ServiceLoader.load(service, Consumer.class);
   *   }
   * }
   * }</pre>
   *
   * <p>An interface bridge requires an InterfaceMethodref constant-pool entry,
   * unlike a bridge in an ordinary class. Checks original method bytes are
   * preserved and ASM reports no errors, then loads the interface and invokes
   * {@code load()} to check the JVM can link the bridge call. A generated proxy
   * stub returns null, so the invocation must also return null.</p>
   */
  @Test
  public void weavesLoadCallInInterface() throws Exception
  {
    ClassWriter writer = consumer();
    writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC | Opcodes.ACC_INTERFACE | Opcodes.ACC_ABSTRACT,
                  "example/Consumer", null, "java/lang/Object", null);
    byte[] original = writer.toByteArray();
    byte[] result = woven(original);
    assertOriginalMethodsUnchanged(original, result);
    assertValidBytecode(result);

    ClassWriter stub = new ClassWriter(ClassWriter.COMPUTE_MAXS);
    stub.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, PROXY, null, "java/lang/Object", null);
    MethodVisitor load = stub.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC, "load",
        WeaverConstants.PROXY_LOAD_DESCRIPTOR, null, null);
    load.visitCode();
    load.visitInsn(Opcodes.ACONST_NULL);
    load.visitInsn(Opcodes.ARETURN);
    load.visitMaxs(0, 0);
    load.visitEnd();
    byte[] proxyBytes = stub.toByteArray();
    ClassLoader loader = new ClassLoader(getClass().getClassLoader())
    {
      @Override
      protected Class<?> findClass(String name) throws ClassNotFoundException
      {
        byte[] definition;
        if (name.equals("example.Consumer"))
          {
            definition = result;
          }
        else if (name.equals(PROXY.replace('/', '.')))
          {
            definition = proxyBytes;
          }
        else
          {
            throw new ClassNotFoundException(name);
          }
        return defineClass(name, definition, 0, definition.length);
      }
    };
    Class<?> consumer = loader.loadClass("example.Consumer");
    assertTrue(consumer.isInterface());
    assertEquals(null, consumer.getMethod("load").invoke(null));
  }


  /**
   * Starts an in-memory Java 17 class named {@code example.Consumer}, equivalent
   * to the following source except that no constructor is generated:
   *
   * <pre>{@code
   * package example;
   *
   * public abstract class Consumer {
   *   public static java.util.ServiceLoader load() {
   *     return java.util.ServiceLoader.load(Runnable.class);
   *   }
   * }
   * }</pre>
   *
   * <p>The raw return type matches the method descriptor; no generic method
   * signature is emitted. The supported {@code load(Class)} call activates
   * weaving. Tests extend this base with constants, fields, methods, or metadata,
   * and some replace the class header to exercise records or interfaces.</p>
   *
   * @return the class writer, ready for test-specific additions, with frames and
   *         maximum stack/local sizes computed by ASM
   */
  private static ClassWriter consumer()
  {
    ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_FRAMES | ClassWriter.COMPUTE_MAXS);
    writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC | Opcodes.ACC_ABSTRACT,
                  "example/Consumer", null, "java/lang/Object", null);
    MethodVisitor method = writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
                                              "load", "()" + DESC, null, null);
    method.visitCode();
    method.visitLdcInsn(Type.getType(Runnable.class));
    method.visitMethodInsn(Opcodes.INVOKESTATIC, JAVA, "load", LOAD, false);
    method.visitInsn(Opcodes.ARETURN);
    method.visitMaxs(0, 0);
    method.visitEnd();
    return writer;
  }

  private static byte[] woven(byte[] original)
  {
    WeavingResult result = ServiceLoaderWeaver.weave(original);
    assertEquals(String.valueOf(result.getException()),
                 WeavingResult.Status.WOVEN, result.getStatus());
    return result.getBytes();
  }

  /**
   * Runs ASM's bytecode verifier and requires no diagnostic output.
   *
   * <pre>{@code
   * Valid bytecode:   diagnostics = ""          -> passes
   * Invalid bytecode: diagnostics = "...error..." -> fails, showing diagnostics
   * }</pre>
   *
   * <p>Checks bytecode structure and data flow without executing the class.
   * Runtime linking and behavior require separate tests.</p>
   *
   * @param bytes class-file bytes to verify
   */
  private static void assertValidBytecode(byte[] bytes)
  {
    StringWriter diagnostics = new StringWriter();
    CheckClassAdapter.verify(new ClassReader(bytes), false, new PrintWriter(diagnostics));
    assertEquals(diagnostics.toString(), "", diagnostics.toString());
  }

  /**
   * Checks every original constant-pool index against the same index after
   * weaving. The following independent examples use illustrative indices, not
   * indices hard-coded into the assertions.
   *
   * <p>UTF-8 entries: replace the internal class name wherever it occurs,
   * including descriptors and generic signatures; unrelated text stays intact.</p>
   * <pre>{@code
   * Original:
   * #10 = Utf8 java/util/ServiceLoader
   * #11 = Utf8 (Ljava/lang/Class;)Ljava/util/ServiceLoader;
   * #12 = Utf8 Ljava/util/ServiceLoader<Ljava/lang/Runnable;>;
   * #13 = Utf8 java.util.ServiceLoader
   * #14 = Utf8 unrelated text
   *
   * Expected after weaving:
   * #10 = Utf8 com/aicas/osgi/spi/proxy/ServiceLoader
   * #11 = Utf8 (Ljava/lang/Class;)Lcom/aicas/osgi/spi/proxy/ServiceLoader;
   * #12 = Utf8 Lcom/aicas/osgi/spi/proxy/ServiceLoader<Ljava/lang/Runnable;>;
   * #13 = Utf8 java.util.ServiceLoader
   * #14 = Utf8 unrelated text
   * }</pre>
   *
   * <p>Supported load Methodref: preserve its index and tag, but retarget its
   * owner and NameAndType. Existing Class and NameAndType payload indices stay
   * unchanged; their referenced UTF-8 text is remapped. Append bridge entries
   * as needed, without removing original entries.</p>
   * <pre>{@code
   * Original:
   * #23 = Methodref   #24.#25 // java/util/ServiceLoader.load
   * #24 = Class      #26     // java/util/ServiceLoader
   * #25 = NameAndType #27:#28 // load:(Ljava/lang/Class;)Ljava/util/ServiceLoader;
   * #26 = Utf8 java/util/ServiceLoader
   * #27 = Utf8 load
   * #28 = Utf8 (Ljava/lang/Class;)Ljava/util/ServiceLoader;
   * #61 = Class      #62     // example/Consumer
   * #62 = Utf8 example/Consumer
   *
   * Expected after weaving:
   * #23 = Methodref   #61.#85 // example/Consumer.serviceLoaderBridge$load
   * #24 = Class      #26     // com/aicas/osgi/spi/proxy/ServiceLoader
   * #25 = NameAndType #27:#28 // load:(Ljava/lang/Class;)Lcom/aicas/osgi/spi/proxy/ServiceLoader;
   * #26 = Utf8 com/aicas/osgi/spi/proxy/ServiceLoader
   * #27 = Utf8 load
   * #28 = Utf8 (Ljava/lang/Class;)Lcom/aicas/osgi/spi/proxy/ServiceLoader;
   * #61 = Class      #62     // example/Consumer
   * #62 = Utf8 example/Consumer
   * #84 = Utf8 serviceLoaderBridge$load
   * #85 = NameAndType #84:#28 // serviceLoaderBridge$load:(Ljava/lang/Class;)Lcom/aicas/osgi/spi/proxy/ServiceLoader;
   * }</pre>
   * <p>For this special Methodref case, the helper checks only the preserved
   * index/tag and the new owner {@code example/Consumer}. The full bridge name,
   * descriptor, and appended entries above illustrate the intended result;
   * they require separate assertions where needed. The pool entry count must
   * not decrease, but this helper does not inspect newly appended slots.</p>
   *
   * <p>Other Methodref entries except the special case above: both payload indices must remain unchanged.</p>
   * <pre>{@code
   * Original:                Expected after weaving:
   * #40 = Methodref #41.#42   #40 = Methodref #41.#42
   * }</pre>
   *
   * <p>Numeric entries retain their payload bytes. Long and double entries
   * also retain their reserved second slots, which have no encoded entry.</p>
   * <pre>{@code
   * Original:                  Expected after weaving:
   * #50 = Integer 42            #50 = Integer 42
   * #51 = Float 1.5f            #51 = Float 1.5f
   * #52 = Long 9876543210L      #52 = Long 9876543210L
   * #53 = (reserved)            #53 = (reserved)
   * #54 = Double 12.5d          #54 = Double 12.5d
   * #55 = (reserved)            #55 = (reserved)
   * }</pre>
   *
   * <p>All remaining entry kinds retain their payload bytes too. Indirect
   * meanings can change through remapped entries, even though these indices
   * stay identical. For example, a MethodHandle still references the same
   * Methodref index after that Methodref is retargeted.</p>
   * <pre>{@code
   * Original:                           Expected after weaving:
   * #70 = Class #10                     #70 = Class #10
   * #71 = String #13                    #71 = String #13
   * #72 = Fieldref #61.#80              #72 = Fieldref #61.#80
   * #73 = InterfaceMethodref #61.#81    #73 = InterfaceMethodref #61.#81
   * #74 = NameAndType #27:#28           #74 = NameAndType #27:#28
   * #75 = MethodHandle 6:#23            #75 = MethodHandle 6:#23
   * #76 = MethodType #11                #76 = MethodType #11
   * #77 = Dynamic #0:#82                #77 = Dynamic #0:#82
   * #78 = InvokeDynamic #1:#83          #78 = InvokeDynamic #1:#83
   * #79 = Module #90                    #79 = Module #90
   * #86 = Package #91                   #86 = Package #91
   * }</pre>
   * <p>These rows illustrate each supported payload category; a particular
   * fixture need not contain every entry kind. Tags must remain unchanged at
   * every non-reserved original index. Actual checks compare binary payloads,
   * not the symbolic comments shown in a disassembly.</p>
   *
   * <p>Method bodies are checked separately by
   * {@link #assertOriginalMethodsUnchanged(byte[], byte[])}.</p>
   *
   * @param original class bytes before weaving
   * @param woven class bytes after weaving
   */
  private static void assertFixedPool(byte[] original, byte[] woven)
  {
    ClassReader before = new ClassReader(original);
    ClassReader after = new ClassReader(woven);
    assertTrue(after.getItemCount() >= before.getItemCount());
    char[] chars = new char[Math.max(before.getMaxStringLength(), after.getMaxStringLength())];
    for (int index = 1; index < before.getItemCount(); index++)
      {
        int a = before.getItem(index);
        int b = after.getItem(index);
        assertEquals(a == 0, b == 0);
        if (a == 0)
          {
            continue;
          }
        int tag = before.readByte(a - 1);
        assertEquals(tag, after.readByte(b - 1));
        if (tag == 1)
          {
            String oldText = utf(original, before, index);
            String expected = oldText.replace(JAVA, PROXY);
            assertEquals("UTF-8 slot " + index, expected, utf(woven, after, index));
          }
        else if (tag == 10)
          {
            // A load Methodref may acquire a new owner/NameAndType, at this same slot.
            String owner = before.readClass(a, chars);
            int nat = before.getItem(before.readUnsignedShort(a + 2));
            String name = before.readUTF8(nat, chars);
            if (JAVA.equals(owner) && "load".equals(name))
              {
                assertEquals("example/Consumer", after.readClass(b, chars));
                continue;
              }
            assertEquals(before.readInt(a), after.readInt(b));
          }
        else
          {
            int size = switch (tag)
              {
              case 3, 4, 9, 11, 12, 17, 18 -> 4;
              case 5, 6 -> 8;
              case 15 -> 3;
              default -> 2;
              };
            for (int offset = 0; offset < size; offset++)
              {
                assertEquals("slot " + index + " offset " + offset,
                              before.readByte(a + offset),
                              after.readByte(b + offset));
              }
          }
      }
  }

  private static String utf(byte[] bytes, ClassReader reader, int index)
  {
    int offset = reader.getItem(index);
    try
      {
        return new DataInputStream(new ByteArrayInputStream(bytes, offset,
                                                            reader.readUnsignedShort(offset) +2)).readUTF();
      }
    catch (IOException exception)
      {
        throw new AssertionError(exception);
      }
  }

  /**
   * Checks that original methods keep exactly the same bytes and order,
   * while generated bridges are appended.
   *
   * <pre>{@code
   * Before:                    After:
   * [0] load()                 [0] load()                 // same bytes
   * [1] choose(boolean)        [1] choose(boolean)        // same bytes
   *                            [2] serviceLoaderBridge$load(Class)
   * }</pre>
   *
   * <p>For each original method, compares the entire {@code method_info}:
   * modifiers, name/descriptor indices, and all attributes, including code,
   * frames, and debug information.</p>
   *
   * <pre>{@code
   * Before load():             After load():
   * ldc #7                    ldc #7
   * invokestatic #23           invokestatic #23           // same instruction bytes
   * areturn                   areturn
   *
   * Pool #23 before: ServiceLoader.load
   * Pool #23 after:  Consumer.serviceLoaderBridge$load    // pool checked separately
   * }</pre>
   *
   * <p>Also requires more methods after weaving. Appended bridge bodies are
   * not compared by this helper.</p>
   *
   * @param original class bytes before weaving
   * @param woven class bytes after weaving
   */
  private static void assertOriginalMethodsUnchanged(byte[] original, byte[] woven)
  {
    List<byte[]> before = methodInfo(original);
    List<byte[]> after = methodInfo(woven);
    assertTrue(after.size() > before.size());
    for (int index = 0; index < before.size(); index++)
      {
        assertArrayEquals("method_info " + index, before.get(index), after.get(index));
      }
  }

  private static List<byte[]> methodInfo(byte[] bytes)
  {
    ByteBuffer input = ByteBuffer.wrap(bytes);
    input.position(new ClassReader(bytes).header + 6);
    input.position(input.position() + 2 +
                   2 * (input.getShort(input.position()) & 65535));
    readMembers(input, bytes); // fields
    return readMembers(input, bytes);
  }

  private static List<byte[]> readMembers(ByteBuffer input, byte[] bytes)
  {
    int count = input.getShort() & 65535;
    List<byte[]> result = new ArrayList<>();
    for (int index = 0; index < count; index++)
      {
        int start = input.position();
        input.position(start + 6);
        int attributes = input.getShort() & 65535;
        for (int attribute = 0; attribute < attributes; attribute++)
          {
            input.getShort();
            int length = input.getInt();
            input.position(input.position() + length);
          }
        result.add(Arrays.copyOfRange(bytes, start, input.position()));
      }
    return result;
  }
