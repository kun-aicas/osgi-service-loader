  /**
   * Adds the following method to the class generated by {@link #consumer()}:
   *
   * <pre>{@code
   * public static String text() {
   *   return "java/util/ServiceLoader";
   * }
   * }</pre>
   *
   * <p>The string literal shares its UTF-8 constant-pool entry with the
   * ServiceLoader class name. Weaving must return {@code UNSAFE_CONSTANT_POOL}
   * and leave the original bytes unchanged rather than alter the string value.</p>
   */
  @Test
  public void leavesClassUnchangedWhenStringLiteralSharesClassName()
  {
    ClassWriter writer = consumer();
    MethodVisitor method = writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
            "text", "()Ljava/lang/String;", null, null);
    method.visitCode();
    method.visitLdcInsn(JAVA); // ASM reuses the UTF-8 entry referenced by the Class entry.
    method.visitInsn(Opcodes.ARETURN);
    method.visitMaxs(0, 0);
    method.visitEnd();
    byte[] original = writer.toByteArray();
    byte[] snapshot = original.clone();
    WeavingResult result = ServiceLoaderWeaver.weave(original);
    assertEquals(WeavingResult.Status.UNSAFE_CONSTANT_POOL, result.getStatus());
    assertSame(original, result.getBytes()); // checks object identity: the weaver returned the original array, not a copy.
    assertArrayEquals(snapshot, result.getBytes()); // verify that the original bytes remain unchanged.
  }

  /**
   * Adds the following method to the class generated by {@link #consumer()},
   * after its existing {@code load()} method:
   *
   * <pre>{@code
   * private static java.util.ServiceLoader serviceLoaderBridge$load(Class service) {
   *   return null;
   * }
   * }</pre>
   *
   * <p>Checks that bridge naming accounts for all declarations before generation:
   * the appended bridge must be named {@code serviceLoaderBridge$load$1} with
   * the proxy return descriptor. Original {@code method_info} bytes must remain
   * unchanged, and ASM verifies the resulting class.</p>
   */
  @Test
  public void suffixesBridgeNameWhenLaterDeclaredMethodCollides()
  {
    ClassWriter writer = consumer(); // load is visited before the conflicting declaration
    MethodVisitor method = writer.visitMethod(Opcodes.ACC_PRIVATE | Opcodes.ACC_STATIC,
            WeaverConstants.BRIDGE_LOAD_NAME, LOAD, null, null);
    method.visitCode();
    method.visitInsn(Opcodes.ACONST_NULL);
    method.visitInsn(Opcodes.ARETURN);
    method.visitMaxs(0, 0);
    method.visitEnd();
    byte[] original = writer.toByteArray();
    byte[] result = woven(original);
    assertOriginalMethodsUnchanged(original, result);
    List<String> methods = new ArrayList<>();
    new ClassReader(result).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public MethodVisitor visitMethod(int access, String name, String descriptor,
                                       String signature, String[] exceptions)
      {
        methods.add(name + descriptor);
        return null;
      }
    }, 0);
    assertTrue(methods.contains(WeaverConstants.BRIDGE_LOAD_NAME + "$1" +
            WeaverConstants.BRIDGE_LOAD_DESCRIPTOR));
    assertValidBytecode(result);
  }

  /**
   * Verifies constant-pool index stability and preservation of original methods
   * using an in-memory {@code example.Consumer} class equivalent to:
   *
   * <pre>{@code
   * package example;
   *
   * public abstract class Consumer {
   *   public static final long LONG_VALUE = 9876543210L;
   *   public static final double DOUBLE_VALUE = 12.5d;
   *   public java.util.ServiceLoader<Runnable>[] loaders;
   *
   *   public static java.util.ServiceLoader load() {
   *     return java.util.ServiceLoader.load(Runnable.class);
   *   }
   *
   *   public static java.util.ServiceLoader<Runnable> choose(boolean enabled) {
   *     if (enabled) {
   *       return java.util.ServiceLoader.load(Runnable.class);
   *     }
   *     return null;
   *   }
   * }
   * }</pre>
   *
   * <p>The base class and {@code load()} method come from {@link #consumer()}.
   * This test adds the array field and its generic signature,
   * {@code choose(boolean)} and its generic signature, stack-map
   * frames, and local-variable debug metadata for {@code enabled}.</p>
   *
   * <p>The constant values of {@code LONG_VALUE} and {@code DOUBLE_VALUE}
   * each occupy two constant-pool indices. The test checks that rewriting
   * preserves these reserved slots.</p>
   *
   * <p>After weaving, existing pool entries retain their indices with the
   * expected remapping, and every original {@code method_info} remains byte-for-byte
   * unchanged. A generated load bridge is appended, and ASM verifies the result.</p>
   */
  @Test
  public void preservesOriginalSlotsAndCompleteMethodInfo()
  {
    ClassWriter writer = consumer();
    writer.visitField(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC | Opcodes.ACC_FINAL,
                      "LONG_VALUE", "J", null, 9876543210L).visitEnd();
    writer.visitField(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC | Opcodes.ACC_FINAL,
                      "DOUBLE_VALUE", "D", null, 12.5d).visitEnd();
    writer.visitField(Opcodes.ACC_PUBLIC, "loaders", "[" + DESC,
                      "[Ljava/util/ServiceLoader<Ljava/lang/Runnable;>;", null).visitEnd();
    MethodVisitor method = writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
        "choose", "(Z)" + DESC, "(Z)Ljava/util/ServiceLoader<Ljava/lang/Runnable;>;", null);
    method.visitCode();
    Label start = new Label();
    Label empty = new Label();
    Label end = new Label();
    method.visitLabel(start);
    method.visitVarInsn(Opcodes.ILOAD, 0);
    method.visitJumpInsn(Opcodes.IFEQ, empty);
    method.visitLdcInsn(Type.getType(Runnable.class));
    method.visitMethodInsn(Opcodes.INVOKESTATIC, JAVA, "load", LOAD, false);
    method.visitInsn(Opcodes.ARETURN);
    method.visitLabel(empty);
    method.visitInsn(Opcodes.ACONST_NULL);
    method.visitInsn(Opcodes.ARETURN);
    method.visitLabel(end);
    method.visitLocalVariable("enabled", "Z", null, start, end, 0);
    method.visitMaxs(0, 0);
    method.visitEnd();
    writer.visitEnd();
    byte[] original = writer.toByteArray();
    byte[] woven = woven(original);
    assertFixedPool(original, woven);// check constant-pool indices and remapping.
    assertOriginalMethodsUnchanged(original, woven); // check method_info bytes and order.
    assertValidBytecode(woven); // check bytecode structure and data flow.
  }

