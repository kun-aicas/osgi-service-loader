  /**
   * Checks that weaving redirects a load method handle even when it is nested
   * inside two dynamic constants. Builds {@code example.Consumer} with only
   * one method, {@code constant()}, containing this structure:
   *
   * <pre>{@code
   * Before weaving:
   * constant() loads outer
   *                  -> inner
   *                     -> handle: java/util/ServiceLoader.load(Class)
   *
   * After weaving:
   * constant() loads outer
   *                  -> inner
   *                     -> handle: example/Consumer.serviceLoaderBridge$load(Class)
   * }</pre>
   *
   * <p>A dynamic constant is a constant whose value the JVM computes through a
   * bootstrap method. Here, outer takes inner as its bootstrap argument, and
   * inner takes the load handle as its argument. ASM builds this fixture
   * directly; there is no ordinary Java source equivalent.</p>
   *
   * <p>There is no ordinary load call: recursive analysis must discover this
   * nested handle to activate weaving. Checks its new owner, name, and
   * proxy-return descriptor, and that original method bytes stay unchanged.
   * Neither constant nor bootstrap method is executed.</p>
   */
  @Test
  public void retargetsHandlesInsideNestedDynamicConstantsWithoutChangingMethods()
  {
    ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
    writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC | Opcodes.ACC_ABSTRACT,
                  "example/Consumer", null, "java/lang/Object", null);
    Handle load = new Handle(Opcodes.H_INVOKESTATIC, JAVA, "load", LOAD, false);
    Handle bootstrap = new Handle(Opcodes.H_INVOKESTATIC, "example/Bootstrap", "constant",
        "(Ljava/lang/invoke/MethodHandles$Lookup;Ljava/lang/String;Ljava/lang/Class;" +
        "Ljava/lang/Object;)Ljava/lang/Object;", false);
    ConstantDynamic nested = new ConstantDynamic("inner", "Ljava/lang/Object;", bootstrap, load);
    ConstantDynamic outer = new ConstantDynamic("outer", "Ljava/lang/Object;", bootstrap, nested);
    MethodVisitor method = writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
                                              "constant", "()Ljava/lang/Object;", null, null);
    method.visitCode();
    method.visitLdcInsn(outer);
    method.visitInsn(Opcodes.ARETURN);
    method.visitMaxs(0, 0);
    method.visitEnd();
    writer.visitEnd();
    byte[] original = writer.toByteArray();
    byte[] result = woven(original);
    assertOriginalMethodsUnchanged(original, result);
    List<Handle> handles = new ArrayList<>();
    new ClassReader(result).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public MethodVisitor visitMethod(int access, String name, String descriptor,
                                        String signature, String[] exceptions)
      {
        return new MethodVisitor(Opcodes.ASM9)
        {
          @Override
          public void visitLdcInsn(Object value)
          {
            if (value instanceof ConstantDynamic dynamic)
              {
                ConstantDynamic inner = (ConstantDynamic) dynamic.getBootstrapMethodArgument(0);
                handles.add((Handle) inner.getBootstrapMethodArgument(0));
              }
          }
        };
      }
    }, 0);
    assertEquals(1, handles.size());
    assertEquals("example/Consumer", handles.get(0).getOwner());
    assertEquals(WeaverConstants.BRIDGE_LOAD_NAME, handles.get(0).getName());
    assertEquals(WeaverConstants.BRIDGE_LOAD_DESCRIPTOR, handles.get(0).getDesc());
  }

