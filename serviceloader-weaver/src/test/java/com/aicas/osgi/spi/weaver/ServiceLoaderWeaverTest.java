  /**
   * Emits bytecode equivalent to:
   *
   * <pre>{@code
   * java.util.ServiceLoader.load(Runnable.class)
   * }</pre>
   *
   * <p>The generated invocation leaves the resulting ServiceLoader instance on
   * the operand stack. The caller must either consume it with another method
   * invocation or remove it using {@link Opcodes#POP}.</p>
   *
   * @param method target method visitor
   */
  private static void emitLoad(MethodVisitor method)
  {
    method.visitLdcInsn(Type.getType(Runnable.class));

    method.visitMethodInsn(Opcodes.INVOKESTATIC,
                           WeaverConstants.JAVA_SERVICE_LOADER,
                           "load",
                           WeaverConstants.JAVA_LOAD_DESCRIPTOR,
                           false);
  }

  /**
   * Generates a synthetic class named {@code test.GeneratedConsumer}.
   *
   * <p>The generated class contains:</p>
   *
   * <ul>
   *   <li>a public default constructor;</li>
   *   <li>a public static {@code consume()} method;</li>
   *   <li>the bytecode supplied by {@code body} inside {@code consume()}.</li>
   * </ul>
   *
   * <p>The class is generated entirely in memory and is never written to a
   * {@code .class} file.</p>
   *
   * @param body callback that emits the body of the generated consume method
   *
   * @return generated JVM class-file bytes
   */
  private static byte[] createClass(MethodBody body)
  {
    ClassWriter writer =
      new ClassWriter(ClassWriter.COMPUTE_MAXS | ClassWriter.COMPUTE_FRAMES);

    writer.visit(Opcodes.V17,
                 Opcodes.ACC_PUBLIC | Opcodes.ACC_SUPER,
                 "test/GeneratedConsumer",
                 null,
                 "java/lang/Object",
                 null);

    addDefaultConstructor(writer);

    MethodVisitor method =
      writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
                         "consume",
                         "()V",
                         null,
                         null);

    method.visitCode();
    body.accept(method);
    method.visitInsn(Opcodes.RETURN);
    method.visitMaxs(0, 0);
    method.visitEnd();

    writer.visitEnd();
    return writer.toByteArray();
  }

  /**
   * Generates a class with a parameterized JDK ServiceLoader field and,
   * optionally, a supported {@code load(Class)} invocation.
   *
   * @param includeSupportedInvocation whether to add a {@code consume()} method
   *        containing a supported load call.
   * @return generated JVM class-file bytes.
   */
  private static byte[] createClassWithServiceLoaderField(boolean includeSupportedInvocation)
  {
    ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS |
                                         ClassWriter.COMPUTE_FRAMES);

    writer.visit(Opcodes.V17,
                 Opcodes.ACC_PUBLIC | Opcodes.ACC_SUPER,
                 "test/GeneratedFieldConsumer",
                 null,
                 "java/lang/Object",
                 null);

    FieldVisitor field =
      writer.visitField(Opcodes.ACC_PRIVATE,
                        "loader",
                        WeaverConstants.JAVA_SERVICE_LOADER_DESCRIPTOR,
                        "Ljava/util/ServiceLoader<Ljava/lang/Runnable;>;",
                        null);

    field.visitEnd();

    addDefaultConstructor(writer);

    if (includeSupportedInvocation)
      {
        MethodVisitor method =
          writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
                             "consume",
                             "()V",
                             null,
                             null);

        method.visitCode();
        emitLoad(method);
        method.visitInsn(Opcodes.POP);
        method.visitInsn(Opcodes.RETURN);
        method.visitMaxs(0, 0);
        method.visitEnd();
      }

    writer.visitEnd();
    return writer.toByteArray();
  }

  /**
   * Generates a consumer that already declares the preferred bridge name.
   *
   * <p>The declared method uses the JDK load descriptor. Type remapping changes
   * it to the proxy descriptor, forcing the weaver to allocate a suffixed
   * bridge name.</p>
   *
   * @return generated JVM class-file bytes
   */
  private static byte[] createClassWithBridgeNameCollision()
  {
    ClassWriter writer =
      new ClassWriter(ClassWriter.COMPUTE_MAXS | ClassWriter.COMPUTE_FRAMES);

    writer.visit(Opcodes.V17,
                 Opcodes.ACC_PUBLIC | Opcodes.ACC_SUPER,
                 "test/GeneratedConsumer",
                 null,
                 "java/lang/Object",
                 null);
    addDefaultConstructor(writer);

    MethodVisitor existingBridge =
        writer.visitMethod(Opcodes.ACC_PRIVATE | Opcodes.ACC_STATIC,
                           WeaverConstants.BRIDGE_LOAD_NAME,
                           WeaverConstants.JAVA_LOAD_DESCRIPTOR,
                           null, null);
    existingBridge.visitCode();
    existingBridge.visitInsn(Opcodes.ACONST_NULL);
    existingBridge.visitInsn(Opcodes.ARETURN);
    existingBridge.visitMaxs(0, 0);
    existingBridge.visitEnd();

    MethodVisitor consumer = writer.visitMethod(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC,
                                                "consume",
                                                "()V",
                                                null,
                                                null);
    consumer.visitCode();
    emitLoad(consumer);
    consumer.visitInsn(Opcodes.POP);
    consumer.visitInsn(Opcodes.RETURN);
    consumer.visitMaxs(0, 0);
    consumer.visitEnd();

    writer.visitEnd();
    return writer.toByteArray();
  }

  /**
   * Adds a public no-argument constructor that invokes {@link Object}'s
   * constructor.
   *
   * @param writer class writer receiving the constructor
   */
  private static void addDefaultConstructor(ClassWriter writer)
  {
    MethodVisitor constructor =
      writer.visitMethod(Opcodes.ACC_PUBLIC,
                         "<init>",
                         "()V",
                         null,
                         null);

    constructor.visitCode();
    constructor.visitVarInsn(Opcodes.ALOAD, 0);

    constructor.visitMethodInsn(Opcodes.INVOKESPECIAL,
                                "java/lang/Object",
                                "<init>",
                                "()V",
                                false);

    constructor.visitInsn(Opcodes.RETURN);
    constructor.visitMaxs(0, 0);
    constructor.visitEnd();
  }

  /**
   * Verifies that a generated class contains an ordinary invocation with the
   * specified JVM instruction details.
   *
   * @param bytes class-file bytes to inspect
   * @param expectedOpcode expected invocation opcode
   * @param expectedOwner expected internal owner name
   * @param expectedName expected method name
   * @param expectedDescriptor expected method descriptor
   */
  private static void assertInvocationExists(byte[] bytes,
                                             int expectedOpcode,
                                             String expectedOwner,
                                             String expectedName,
                                             String expectedDescriptor)
  {
    final List<Invocation> invocations = new ArrayList<Invocation>();

    new ClassReader(bytes).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public MethodVisitor visitMethod(int access,
                                       String name,
                                       String descriptor,
                                       String signature,
                                       String[] exceptions)
      {
        return new MethodVisitor(Opcodes.ASM9)
        {
          @Override
          public void visitMethodInsn(int opcode,
                                      String owner,
                                      String methodName,
                                      String methodDescriptor,
                                      boolean isInterface)
          {
            invocations.add(new Invocation(
                                           opcode,
                                           owner,
                                           methodName,
                                           methodDescriptor));
          }
        };
      }
    }, ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);

    Invocation expected = new Invocation(expectedOpcode, expectedOwner,
                                         expectedName,
                                         expectedDescriptor);

    assertTrue("Expected invocation was not found. Existing invocations: " +
               invocations,
               invocations.contains(expected));
  }

  /**
   * Verifies a generated bridge's modifiers, caller-class literal, and proxy
   * {@code load} invocation.
   *
   * @param bytes class-file bytes to inspect
   * @param className internal name of the woven class
   * @param bridgeName generated bridge method name
   * @param bridgeDescriptor generated bridge descriptor
   * @param proxyDescriptor proxy load descriptor
   */
  private static void assertBridgeForwardsToProxy(byte[] bytes,
                                                  String className,
                                                  String bridgeName,
                                                  String bridgeDescriptor,
                                                  String proxyDescriptor)
  {
    final boolean[] hasClassLiteral = { false };
    final boolean[] forwardsToProxy = { false };

    new ClassReader(bytes).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public MethodVisitor visitMethod(int access,
                                       String name,
                                       String descriptor,
                                       String signature,
                                       String[] exceptions)
      {
        if (!bridgeName.equals(name) ||
            !bridgeDescriptor.equals(descriptor))
          {
            return null;
          }
        assertTrue((access & Opcodes.ACC_PRIVATE) != 0);
        assertTrue((access & Opcodes.ACC_STATIC) != 0);
        assertTrue((access & Opcodes.ACC_SYNTHETIC) != 0);
        return new MethodVisitor(Opcodes.ASM9)
        {
          @Override
          public void visitLdcInsn(Object value)
          {
            if (value instanceof Type &&
                className.equals(((Type) value).getInternalName()))
              {
                hasClassLiteral[0] = true;
              }
          }

          @Override
          public void visitMethodInsn(int opcode,
                                      String owner,
                                      String name,
                                      String descriptor,
                                      boolean isInterface)
          {
            if (opcode == Opcodes.INVOKESTATIC &&
                WeaverConstants.OSGI_SERVICE_LOADER.equals(owner) &&
                "load".equals(name) &&
                proxyDescriptor.equals(descriptor))
              {
                forwardsToProxy[0] = true;
              }
          }
        };
      }
    }, ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);

    assertTrue("Bridge did not load the woven class literal", hasClassLiteral[0]);
    assertTrue("Bridge did not forward to the proxy ServiceLoader", forwardsToProxy[0]);
  }

  /**
   * Verifies that an LDC constant contains a method handle with the expected
   * target.
   *
   * @param bytes class-file bytes to inspect
   * @param expectedTag expected ASM handle tag
   * @param expectedOwner expected internal owner name
   * @param expectedName expected method name
   * @param expectedDescriptor expected method descriptor
   */
  private static void assertMethodHandleExists(byte[] bytes,
                                               int expectedTag,
                                               String expectedOwner,
                                               String expectedName,
                                               String expectedDescriptor)
  {
    final boolean[] found = { false };
    new ClassReader(bytes).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public MethodVisitor visitMethod(int access,
                                       String name,
                                       String descriptor,
                                       String signature,
                                       String[] exceptions)
      {
        return new MethodVisitor(Opcodes.ASM9)
        {
          @Override
          public void visitLdcInsn(Object value)
          {
            if (value instanceof Handle)
              {
                Handle handle = (Handle) value;
                found[0] |= handle.getTag() == expectedTag &&
                            expectedOwner.equals(handle.getOwner()) &&
                            expectedName.equals(handle.getName()) &&
                            expectedDescriptor.equals(handle.getDesc());
              }
          }
        };
      }
    }, ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);
    assertTrue("Expected method handle was not found", found[0]);
  }

  /**
   * Verifies that selected bytecode locations no longer reference
   * java/util/ServiceLoader.
   *
   * <p>The inspection currently covers:</p>
   *
   * <ul>
   *   <li>field descriptors;</li>
   *   <li>field generic signatures;</li>
   *   <li>method descriptors;</li>
   *   <li>method generic signatures;</li>
   *   <li>method invocation owners;</li>
   *   <li>method invocation descriptors;</li>
   *   <li>type instructions;</li>
   *   <li>class literals loaded using LDC.</li>
   * </ul>
   *
   * @param bytes woven class-file bytes
   */
  private static void assertNoReferenceToJavaServiceLoader(byte[] bytes)
  {
    final List<String> references =
      new ArrayList<String>();

    new ClassReader(bytes).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public FieldVisitor visitField(int access,
                                     String name,
                                     String descriptor,
                                     String signature,
                                     Object value)
      {
        collectJavaServiceLoaderReference(references,
                                          "field " + name,
                                          descriptor);

        collectJavaServiceLoaderReference(references,
                                          "field signature " + name,
                                          signature);

        return null;
      }

      @Override
      public MethodVisitor visitMethod(int access,
                                       String name,
                                       String descriptor,
                                       String signature,
                                       String[] exceptions)
      {
        collectJavaServiceLoaderReference(references,
                                          "method " + name,
                                          descriptor);

        collectJavaServiceLoaderReference(references,
                                          "method signature " + name,
                                          signature);

        return new MethodVisitor(Opcodes.ASM9)
        {
          @Override
          public void visitMethodInsn(int opcode,
                                      String owner,
                                      String methodName,
                                      String methodDescriptor,
                                      boolean isInterface)
          {
            if (WeaverConstants.JAVA_SERVICE_LOADER.equals(owner))
              {
                references.add("invocation owner " +
                               owner + "." +
                               methodName +
                               methodDescriptor);
              }

            collectJavaServiceLoaderReference(references,
                                              "invocation descriptor " + methodName,
                                              methodDescriptor);
          }

          @Override
          public void visitTypeInsn(int opcode,
                                    String type)
          {
            if (WeaverConstants.JAVA_SERVICE_LOADER.equals(type))
              {
                references.add("type instruction " +
                               type);
              }
          }

          @Override
          public void visitLdcInsn(Object value)
          {
            if (value instanceof Type)
              {
                Type type = (Type) value;

                if (type.getSort() == Type.OBJECT &&
                    WeaverConstants.JAVA_SERVICE_LOADER.equals(type.getInternalName()))
                  {
                    references.add("class literal " + value);
                  }
              }
          }
        };
      }
    }, 0);

    assertTrue("Remaining java.util.ServiceLoader references: " + references,
               references.isEmpty());
  }

  /**
   * Records only bytecode locations whose text contains the JDK ServiceLoader
   * internal name.
   *
   * @param references mutable list of detected references
   * @param location description of the bytecode location
   * @param value descriptor or signature to inspect
   */
  private static void collectJavaServiceLoaderReference(List<String> references,
                                       String location,
                                       String value)
  {
    if (value != null &&
        value.contains(WeaverConstants.JAVA_SERVICE_LOADER))
      {
        references.add(location + ": " + value);
      }
  }

  /**
   * Reads the names and descriptors of all fields in a generated class.
   *
   * @param bytes class-file bytes to inspect
   * @return field descriptions in class-file order
   */
  private static List<FieldDescription> readFields(byte[] bytes)
  {
    final List<FieldDescription> fields =
      new ArrayList<FieldDescription>();

    new ClassReader(bytes).accept(new ClassVisitor(Opcodes.ASM9)
    {
      @Override
      public FieldVisitor visitField(int access,
                                     String name,
                                     String descriptor,
                                     String signature,
                                     Object value)
      {
        fields.add(new FieldDescription(name, descriptor));
        return null;
      }
    }, ClassReader.SKIP_CODE | ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);
    return fields;
  }

